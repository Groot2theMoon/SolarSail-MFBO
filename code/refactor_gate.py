def _label_dir(label):
    return os.path.join(BASELINE_DIR, label)


def _ensure(path):
    if not os.path.isdir(path):
        os.makedirs(path)
    return path


def _expand(patterns):
    out = []
    for pat in patterns or []:
        hits = sorted(glob.glob(pat))
        if not hits and os.path.exists(pat):
            hits = [pat]
        if not hits:
            print('  !!! 패턴이 아무것도 잡지 못했다: %s' % pat)
        out.extend(hits)
    #   같은 파일을 두 번 세지 않는다(겹치는 패턴 허용).
    seen, uniq = set(), []
    for p in out:
        key = os.path.abspath(p)
        if key not in seen:
            seen.add(key)
            uniq.append(p)
    return uniq


def _save_json(path, obj):
    with io.open(path, 'w', encoding='utf-8') as f:
        f.write(json.dumps(obj, ensure_ascii=False, indent=1, sort_keys=True))


def _load_json(path):
    with io.open(path, 'r', encoding='utf-8') as f:
        return json.load(f)


def _save_norm(path, text):
    """정규화 덱을 gzip 으로 남긴다(사람이 diff 로 읽을 수 있게)."""
    with gzip.open(path, 'wb') as f:
        f.write(text.encode('utf-8'))


def _load_norm(path):
    with gzip.open(path, 'rb') as f:
        return f.read().decode('utf-8')


