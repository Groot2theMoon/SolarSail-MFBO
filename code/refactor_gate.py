# G2/G3 - key=value
# ---------------------------------------------------------------------------
_KV_LINE = re.compile(r'^\s*([A-Za-z_][\w.\-]*)\s*=\s*(.*?)\s*$')
_KV_ANY = re.compile(r'([A-Za-z_][\w./\-]*)=([^\s,;]+)')


def _num(v):
    """'1e-3' / ' 0.001 ' / '(-3.4e-12' -> float. 숫자가 아니면 None.

    괄호·쉼표는 프로브 로그가 값을 `n_eq=(-3.45e-12 ...` 처럼 잘라 담기 때문이다.
    날짜(`2026-11-04 15:50:59`)는 숫자로 읽히지 않는다 - 그런 키는 VOLATILE_KEYS 에 둔다.
    """
    s = str(v).strip().strip('()[]{},;')
    try:
        return float(s)
    except (TypeError, ValueError):
        return None


def parse_results(path, volatile=VOLATILE_KEYS):
    """results_*.txt -> [(key, value)] (줄 순서 유지, volatile 키는 제외)."""
    rows = []
    with io.open(path, 'r', encoding='utf-8', errors='replace') as f:
        for line in f:
            m = _KV_LINE.match(line)
            if not m:
                continue
            if m.group(1) in volatile:
                continue
            rows.append((m.group(1), m.group(2)))
    return rows


def parse_probe(path):
    """프로브 로그 -> [(key, value)] 다중집합(같은 키 반복 허용)."""
    rows = []
    with io.open(path, 'r', encoding='utf-8', errors='replace') as f:
        for line in f:
            for m in _KV_ANY.finditer(line):
                rows.append((m.group(1), m.group(2)))
    return rows


def _basename_if_abs_path(v):
    """절대경로 값이면 basename, 아니면 None.

    [2026-11-04] baseline 은 임시 사본에서, check 는 정본 체크아웃에서 돌 수 있다.
    절대경로(`r13_ct_odb`, `table`, `cwd`)는 **실행 위치**이지 모델 정의가 아니므로
    basename 만 비교한다(G1 이 덱 경로를 정규화하는 것과 같은 이유).
    """
    s = str(v).strip()
    if re.match(r'^(?:[A-Za-z]:[\\/]|\\\\)', s):
        return os.path.basename(s.replace('\\', '/'))
    return None


def _same_value(a, b):
    if a == b:
        return True
    pa, pb = _basename_if_abs_path(a), _basename_if_abs_path(b)
    if pa is not None and pb is not None:
        return pa.lower() == pb.lower()
    fa, fb = _num(a), _num(b)
    if fa is not None and fb is not None:
        if fa == fb:
            return True
        scale = max(abs(fa), abs(fb))
        return scale > 0 and abs(fa - fb) / scale <= REL_TOL
    return False


def diff_kv(old, new, label_old='baseline', label_new='now'):
    """[(key, kind, old, new)] - kind: 'changed' | 'missing' | 'added' | 'multiplicity'."""
    problems = []
    od, nd = {}, {}
    #   volatile 키는 **양쪽**에서 뺀다. baseline 파일이 예전 volatile 규칙으로 만들어졌어도
    #   (예: r13_ct_odb_mtime 이 들어 있는 p0) 값 비교에서 문제가 되지 않게 한다.
    for k, v in old:
        if k not in VOLATILE_KEYS:
            od.setdefault(k, []).append(v)
    for k, v in new:
        if k not in VOLATILE_KEYS:
            nd.setdefault(k, []).append(v)
    for k in sorted(set(od) | set(nd)):
        ov, nv = od.get(k, []), nd.get(k, [])
        if not nv:
            problems.append((k, 'missing', ' | '.join(ov), '-'))
        elif not ov:
            problems.append((k, 'added', '-', ' | '.join(nv)))
        elif len(ov) != len(nv):
            problems.append((k, 'multiplicity', '%d values' % len(ov),
                             '%d values' % len(nv)))
        elif not all(_same_value(a, b) for a, b in zip(ov, nv)):
            problems.append((k, 'changed', ' | '.join(ov), ' | '.join(nv)))
    return problems


