HERE = os.path.dirname(os.path.abspath(__file__))
BASELINE_DIR = os.path.join(HERE, 'baseline')

# 결과 txt 에서 매 런마다 달라지는 키. 값 비교에서 뺀다(키 자체는 존재해야 한다).
#   r13_ct_odb_mtime: ODB 파일 수정시각 - 런할 때마다 다르다(2026-11-04 실측).
VOLATILE_KEYS = ('timestamp', 'r13_ct_odb_mtime')

# G2/G3 숫자 비교 상대오차. 2026-11-04 실측(같은 코드·같은 기계로 LF+HF를 **재해석**):
#   최대 상대차 1.44e-6 (slope_f2_p95), hf 는 1.5e-9. 절대오차 0 을 요구하면 재현 불가능한 FAIL.
#   G1(덱 정규화 sha256)은 그대로 오차 0 이고, 이 허용오차는 **해석기 잡음**만 흡수한다.
#   1e-5 = 실측 최대의 약 7배. 이보다 큰 변화는 모델/코드 변경으로 본다.
REL_TOL = 1.0e-5

# ---------------------------------------------------------------------------
# G1 - 덱 정규화
# ---------------------------------------------------------------------------
#   Abaqus writeInput 산출물의 머리말은 ** 로 시작하는 주석이다:
#       *Heading
#       ** Job name: HF_Postbuckle_u3free Model name: SailModel_Triangle
#       ** Generated by: Abaqus/CAE 2023
#   -> ** 줄과 *Heading 뒤 자유텍스트 줄을 지운다.
_ABS_PATH = re.compile(r'(?i)(?:[a-z]:/|//)[^,\s]*')


def _norm_path(m):
    """절대경로 -> '@PATH@/<basename>'. basename 은 잡/스텝 이름을 담으므로 남긴다."""
    s = m.group(0).rstrip('/')
    base = s.rsplit('/', 1)[-1]
    return '@PATH@/' + base if base else '@PATH@'


def normalize_deck(text):
    """덱 텍스트 -> (정규화 텍스트, 정규화로 지운 줄 수).

    지우는 것: 빈 줄, '**' 주석 줄, '*Heading' 뒤 자유텍스트 줄.
    바꾸는 것: 개행 통일(\\n), 줄끝 공백 제거, 역슬래시 -> 슬래시, 절대경로 -> @PATH@/base.
    남기는 것: 그 밖의 모든 문자(숫자 포함) 그대로.
    """
    text = text.replace('\r\n', '\n').replace('\r', '\n').replace('\\', '/')
    out, dropped = [], 0
    in_heading = False
    for raw in text.split('\n'):
        line = raw.rstrip()
        stripped = line.strip()
        if not stripped:
            dropped += 1
            continue
        if stripped.startswith('**'):
            dropped += 1
            continue
        if stripped.upper().startswith('*HEADING'):
            #   '*Heading' 는 남기고 그 뒤 자유텍스트(잡 이름/날짜/경로)는 버린다.
            out.append('*Heading')
            in_heading = True
            dropped += 1
            continue
        if in_heading and not stripped.startswith('*'):
            dropped += 1
            continue
        in_heading = False
        out.append(_ABS_PATH.sub(_norm_path, line))
    return '\n'.join(out) + '\n', dropped


def deck_digest(path):
    """(sha256, 정규화 텍스트, 지운 줄 수)."""
    with io.open(path, 'r', encoding='latin-1') as f:
        raw = f.read()
    norm, dropped = normalize_deck(raw)
    h = hashlib.sha256(norm.encode('utf-8')).hexdigest()
    return h, norm, dropped


