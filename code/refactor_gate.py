"""refactor_gate.py - 리팩토링 회귀 게이트 (P0 동결 장치).

목적
    run_abaqus.py 를 쪼개는 동안 **덱과 결과가 한 글자도 변하지 않았음**을 기계로 증명한다.
    사람이 눈으로 두 .inp 를 비교하는 방식은 2894줄 스크립트에서는 성립하지 않는다.

세 게이트
    G1 deck    : *.inp -> 정규화 텍스트 -> sha256.        (job name / 날짜 / 절대경로 제거)
    G2 results : results_*.txt -> key=value -> 값 단위 비교. (상대 1e-5, timestamp/mtime 제외)
    G3 probe   : 프로브 로그 -> key=value 다중집합 비교.   (base_state_probe 등)

사용 (리팩토링 **전**에 capture, **후**에 check - 같은 인자로)
    python refactor_gate.py capture --label p0 --deck "aba/*.inp" --results "results/results_*.txt"
    python refactor_gate.py check   --label p0 --deck "aba/*.inp" --results "results/results_*.txt"
    python refactor_gate.py snapshot --label p0
    python refactor_gate.py selftest

    --probe 는 여러 번 줄 수 있다:  --probe "aba/base_state_probe.log" --probe "aba/LF.log"

종료코드
    0 = 모든 게이트 PASS, 1 = 하나 이상 FAIL, 2 = 사용법/IO 오류

설계 원칙
    - Python 2.7(Abaqus 내장)과 3.x 에서 같이 돈다: f-string / subprocess.run / print() 금지.
    - 표준 라이브러리만 쓴다(difflib, hashlib, gzip, json, glob).
    - G1 은 **숫자를 정규화하지 않는다.** 반올림 허용은 "조용한 모델 변경"을 통과시키므로
      게이트가 아니다. 부동소수 표기 차이는 FAIL 로 뜨고, 사람이 diff 로 판단한다.
"""
