def _sha256_file(path):
    h = hashlib.sha256()
    with io.open(path, 'rb') as f:
        while True:
            b = f.read(65536)
            if not b:
                break
            h.update(b)
    return h.hexdigest()


def _count_lines(path):
    #   wc -l 과 같은 정의: 개행 **문자** 수. 마지막 줄에 개행이 없으면 세지 않는다.
    #   (예전 구현은 `for line in f` 로 개행 없는 마지막 줄까지 세어 wc -l 보다 2줄 많았다.)
    n = 0
    with io.open(path, 'rb') as f:
        while True:
            chunk = f.read(65536)
            if not chunk:
                break
            n += chunk.count(b'\n')
    return n


def cmd_snapshot(args):
    root = _ensure(_label_dir(args.label))
    rows = []
    src = os.path.join(HERE, '*.py')
    for p in sorted(glob.glob(src)):
        rows.append('%-34s %8d  %s' % (os.path.basename(p), _count_lines(p),
                                        _sha256_file(p)))
    total = sum(int(r.split()[1]) for r in rows) if rows else 0
    header = ('# refactor_gate snapshot label=%s  %s\n'
              '# file                               lines  sha256\n'
              '# TOTAL %d files %d lines\n'
              % (args.label, time.strftime('%Y-%m-%d %H:%M:%S'), len(rows), total))
    out = os.path.join(root, 'source_manifest.txt')
    with io.open(out, 'w', encoding='utf-8') as f:
        f.write(header)
        f.write('\n'.join(rows) + '\n')
    print(header.strip())
    print('[snapshot] %s' % out)
    return 0


