def main(argv):
    args = list(argv)
    if not args or args[0] in ('-h', '--help', 'help'):
        print(__doc__)
        return 0 if args else 2
    cmd = args.pop(0)
    label = None
    deck, results, probe = [], [], []
    while args:
        a = args.pop(0)
        if a == '--label':
            label = args.pop(0)
        elif a == '--deck':
            deck.append(args.pop(0))
        elif a == '--results':
            results.append(args.pop(0))
        elif a == '--probe':
            probe.append(args.pop(0))
        else:
            print('!!! 알 수 없는 인자: %s' % a)
            return 2

    class _A(object):
        pass
    ns = _A()
    ns.label = label
    ns.deck = deck
    ns.results = results
    ns.probe = probe

    if cmd == 'capture':
        if not label:
            print('!!! --label 필요')
            return 2
        return cmd_capture(ns)
    if cmd == 'check':
        if not label:
            print('!!! --label 필요')
            return 2
        return cmd_check(ns)
    if cmd == 'snapshot':
        if not label:
            print('!!! --label 필요')
            return 2
        return cmd_snapshot(ns)
    if cmd == 'selftest':
        return cmd_selftest(ns)
    print('!!! 알 수 없는 명령: %s' % cmd)
    return 2


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
