def cmd_capture(args):
    root = _ensure(_label_dir(args.label))
    decks = _expand(args.deck)
    results = _expand(args.results)
    probes = _expand(args.probe)
    if not (decks or results or probes):
        print('!!! 잡은 파일이 없다. --deck/--results/--probe 를 확인할 것.')
        return 2

    meta = {'label': args.label, 'captured': time.strftime('%Y-%m-%d %H:%M:%S'),
            'gate': {}, 'files': {}}
    if decks:
        d = _ensure(os.path.join(root, 'deck'))
        for p in decks:
            h, norm, dropped = deck_digest(p)
            name = os.path.basename(p)
            _save_norm(os.path.join(d, name + '.norm.gz'), norm)
            meta['files'].setdefault('deck', {})[name] = h
            print('[G1 capture] %-40s %s (정규화 %d줄 제거)' % (name, h[:16], dropped))
        meta['gate']['G1'] = len(decks)
    if results:
        d = _ensure(os.path.join(root, 'results'))
        for p in results:
            rows = parse_results(p)
            name = os.path.basename(p)
            _save_json(os.path.join(d, name + '.kv.json'), rows)
            meta['files'].setdefault('results', {})[name] = len(rows)
            print('[G2 capture] %-40s %d keys' % (name, len(rows)))
        meta['gate']['G2'] = len(results)
    if probes:
        d = _ensure(os.path.join(root, 'probe'))
        for p in probes:
            rows = parse_probe(p)
            name = os.path.basename(p)
            _save_json(os.path.join(d, name + '.kv.json'), rows)
            meta['files'].setdefault('probe', {})[name] = len(rows)
            print('[G3 capture] %-40s %d kv 쌍' % (name, len(rows)))
        meta['gate']['G3'] = len(probes)
    _save_json(os.path.join(root, 'capture.json'), meta)
    print('\n[baseline] %s  (deck=%d results=%d probe=%d)'
          % (root, len(decks), len(results), len(probes)))
    return 0


def _diff_decks(old_text, new_text, limit=25):
    out = []
    for line in difflib.unified_diff(old_text.split('\n'), new_text.split('\n'),
                                     fromfile='baseline', tofile='now', lineterm='', n=1):
        out.append(line)
        if len(out) >= limit:
            out.append('  ... (생략)')
            break
    return out


def cmd_check(args):
    root = _label_dir(args.label)
    cap_path = os.path.join(root, 'capture.json')
    if not os.path.exists(cap_path):
        print('!!! baseline 없음: %s  (먼저 capture 할 것)' % cap_path)
        return 2
    meta = _load_json(cap_path)
    fails = 0

    #   요청하지 않은 게이트는 건너뛴다(부분 검사 허용). 요청했는데 산출물이 없으면 FAIL 이다.
    #   capture 와 check 에 **같은 인자**를 주는 것이 정상 사용법이다.
    # ---- G1 --------------------------------------------------------------
    decks = _expand(args.deck)
    want = sorted((meta['files'].get('deck') or {}).keys())
    if want and not args.deck:
        print('[G1 deck] (요청 없음 - 건너뜀, baseline %d개)' % len(want))
    elif want or decks:
        print('[G1 deck]')
        got = dict((os.path.basename(p), p) for p in decks)
        for name in want:
            if name not in got:
                print('  FAIL  %-38s baseline 에는 있는데 지금 없다' % name)
                fails += 1
                continue
            h, norm, _ = deck_digest(got[name])
            if h == meta['files']['deck'][name]:
                print('  PASS  %-38s %s (바이트 동일)' % (name, h[:16]))
            else:
                print('  FAIL  %-38s %s != %s' % (name, h[:16],
                                                  meta['files']['deck'][name][:16]))
                old = _load_norm(os.path.join(root, 'deck', name + '.norm.gz'))
                for ln in _diff_decks(old, norm):
                    print('        ' + ln)
                fails += 1
        for name in sorted(set(got) - set(want)):
            print('  FAIL  %-38s baseline 에 없는 새 덱' % name)
            fails += 1

    # ---- G2 --------------------------------------------------------------
    results = _expand(args.results)
    want = sorted((meta['files'].get('results') or {}).keys())
    if want and not args.results:
        print('[G2 results] (요청 없음 - 건너뜀, baseline %d개)' % len(want))
    elif want or results:
        print('[G2 results]')
        got = dict((os.path.basename(p), p) for p in results)
        for name in want:
            if name not in got:
                print('  FAIL  %-38s 지금 없다' % name)
                fails += 1
                continue
            old = _load_json(os.path.join(root, 'results', name + '.kv.json'))
            old = [(k, v) for k, v in old]
            probs = diff_kv(old, parse_results(got[name]))
            if probs:
                print('  FAIL  %-38s %d개 키 불일치' % (name, len(probs)))
                for k, kind, a, b in probs[:20]:
                    print('        %-22s %-12s baseline=%s  now=%s' % (k, kind, a, b))
                fails += 1
            else:
                print('  PASS  %-38s %d keys 동일' % (name, len(old)))
        for name in sorted(set(got) - set(want)):
            print('  FAIL  %-38s baseline 에 없는 새 결과' % name)
            fails += 1

    # ---- G3 --------------------------------------------------------------
    probes = _expand(args.probe)
    want = sorted((meta['files'].get('probe') or {}).keys())
    if want and not args.probe:
        print('[G3 probe] (요청 없음 - 건너뜀, baseline %d개)' % len(want))
    elif want or probes:
        print('[G3 probe]')
        got = dict((os.path.basename(p), p) for p in probes)
        for name in want:
            if name not in got:
                print('  FAIL  %-38s 지금 없다' % name)
                fails += 1
                continue
            old = _load_json(os.path.join(root, 'probe', name + '.kv.json'))
            old = [(k, v) for k, v in old]
            probs = diff_kv(old, parse_probe(got[name]))
            if probs:
                print('  FAIL  %-38s %d개 kv 불일치' % (name, len(probs)))
                for k, kind, a, b in probs[:20]:
                    print('        %-22s %-12s baseline=%s  now=%s' % (k, kind, a, b))
                fails += 1
            else:
                print('  PASS  %-38s %d kv 동일' % (name, len(old)))
        for name in sorted(set(got) - set(want)):
            print('  FAIL  %-38s baseline 에 없는 새 프로브' % name)
            fails += 1

    print('\n[gate] %s' % ('PASS' if not fails else 'FAIL (%d)' % fails))
    return 0 if not fails else 1


