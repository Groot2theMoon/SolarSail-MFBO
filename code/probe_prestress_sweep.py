#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""케이블 프리스트레스 스윕 — 중앙 von Mises 가 1 psi(6895 Pa)가 되는 운용점을 찾는다.

    python probe_prestress_sweep.py --dry-run      # config 생성/경로만 검증
    python probe_prestress_sweep.py                # LF 4점 실행 (~40 s/점)

## 왜 DISP_GLOBAL 이 아니라 CABLE_PRESTRESS 인가

현재 기본값 `PAPER_MATCH = True` -> `LOAD_MODE = 'cable_stress'`(run_abaqus.py:107)이고,
이 경로에서 프리텐션은 **케이블 초기응력**으로만 들어간다:

    my_model.Stress(sigma11=CABLE_PRESTRESS)      # 케이블 3개
    my_model.Stress(sigma11=CABLE_PRESTRESS*d_c)  # 클램프 케이블

같은 경로에서 `_DISP_PRE = 0.0`(run_abaqus.py:545)이므로 꼭짓점 RP 는 0 에 머물고,
`CLAMP_PULL = DISP_GLOBAL*d_c` 는 `LOAD_MODE == 'disp'` 분기에서만 계산된다(:1654).
즉 **DISP_GLOBAL 은 이 경로에서 기계적 역할이 없다**(로그/fingerprint 에만 등장).
운용점을 움직이는 노브는 `CABLE_PRESTRESS` 다.

## 왜 LF 만 도나

Galhofo 2022 §3.3 의 7000 Pa(Boni 2016 의 von Mises 1 psi)는 **완전 막의 프리스트레스 상태**에서
중앙 응력이다. HF 는 같은 프리스트레스에 기하 임퍼펙션을 더하므로, 운용점 질문은 LF 가 정확하고
10배 싸다.

## 주의

- `clean_lf: true` 로 옛 LF ODB 를 지운다(CABLE_PRESTRESS 는 LF 지문에 포함되지만, 파일명이
  같아 지우는 편이 확실하다).
- 스윕 후 기준값(`--restore`, 기본 2.69e7 Pa)으로 되돌린다. 안 하면 이후 HF 의 짝 LF ODB 가
  마지막 스윕 값에 남는다.
- 점별 results txt 는 LF 런이 'w' 로 덮어쓰므로, 시작 전에 백업하고 끝나면 되돌린다.
"""
from __future__ import print_function

import argparse
import csv
import io
import json
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import aba_imperfection as A                                                # noqa: E402

KV = re.compile(r'centre_mean_pa=([-\d.eE+]+)\s+centre_minp_pa=([-\d.eE+]+)'
                r'(?:\s+centre_mises_pa=([-\d.eE+]+))?')
TARGET = 6895.0            # 1 psi (Boni 2016, Galhofo 2022 의 '7000 Pa' 원 정의)
CABLE_AREA = 7.853981633974483e-07   # m^2, r=5e-4


def build_config(base, cable_pa, x_c, d_c, out_path):
    cfg = json.load(io.open(base, encoding='utf-8'))
    cfg['CABLE_PRESTRESS'] = cable_pa
    #   구 disp 경로 키가 남아 있으면 지운다 — 이 경로에서는 무효지만, 읽는 사람이
    #   "DISP_GLOBAL 이 운용점"이라고 오독하는 것을 막는다.
    cfg.pop('DISP_GLOBAL', None)
    cfg['_comment'] = (
        'Probe config generated by probe_prestress_sweep.py (operating-point sweep). '
        'CABLE_PRESTRESS IS SET HERE on purpose - do not copy this file as a run config. '
        'All other keys are inherited from %s.' % os.path.basename(base))
    cfg['RUN'] = {
        'x_c': x_c, 'd_c': d_c,
        'fidelities': ['LF'],
        'make_seed': False, 'force_seed': False,
        'buckle': False, 'clean_lf': True,
    }
    io.open(out_path, 'w', encoding='utf-8').write(
        json.dumps(cfg, indent=2, ensure_ascii=False) + '\n')


def run(cmd, dry):
    #   Windows 에서 `abaqus` 는 abaqus.bat 이라 shell=False 로는 WinError 2 가 난다.
    #   저장소의 run_analysis.py / make_seed.py 와 같은 규칙(shell=True + 문자열)을 쓴다.
    line = subprocess.list2cmdline(cmd) if isinstance(cmd, (list, tuple)) else cmd
    print('  $', line)
    if dry:
        return 0, ''
    p = subprocess.Popen(line, shell=True, cwd=HERE, stdout=subprocess.PIPE,
                         stderr=subprocess.STDOUT, universal_newlines=True)
    assert p.stdout is not None
    out = []
    for line in p.stdout:
        out.append(line)
        if 'centre_minp_pa' in line or 'RESULTS:' in line or 'Traceback' in line:
            print('     ', line.rstrip()[:200])
    return p.wait(), ''.join(out)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--x_c', type=float, default=0.2)
    ap.add_argument('--d_c', type=float, default=1e-4)
    ap.add_argument('--config', default=os.path.join('configs', 'seed.json'))
    ap.add_argument('--prestress', type=float, nargs='+',
                    default=[1.4e7, 1.7e7, 2.0e7, 2.3e7],
                    help='케이블 초기응력 [Pa]. 기본값은 1 psi 교차점(선형 추정 1.71e7)을 감싼다')
    ap.add_argument('--restore', type=float, default=2.69e7,
                    help='스윕 후 되돌릴 CABLE_PRESTRESS [Pa] (0 이면 생략)')
    ap.add_argument('--dry-run', action='store_true')
    a = ap.parse_args(argv)

    base = a.config if os.path.isabs(a.config) else os.path.join(HERE, a.config)
    tmp = os.path.join(HERE, 'configs', '_probe_prestress.json')
    odb = os.path.join(HERE, 'aba', A.lf_odb_name(a.x_c, a.d_c))
    csv_path = os.path.join(HERE, 'results', 'probe_prestress_centre.csv')
    live = os.path.join(HERE, 'results', 'results_xc%s_dc%s.txt'
                        % (A.value_tag(a.x_c), A.value_tag(a.d_c)))
    backup = os.path.join(HERE, 'results', 'probe_backup_%s' % os.path.basename(live))
    rows = []

    #   LF 런은 점별 results txt 를 'w' 로 덮어쓴다 -> 기존 HF 기록을 먼저 보관한다.
    if not a.dry_run and os.path.exists(live):
        shutil.copy2(live, backup)
        print('[PROBE] 기존 결과 백업: %s' % os.path.basename(backup))

    print('[PROBE] x_c=%g d_c=%g  LF ODB=%s' % (a.x_c, a.d_c, os.path.basename(odb)))
    for cable_pa in a.prestress:
        print('\n[PROBE] CABLE_PRESTRESS = %.4g Pa  (%.2f N/cable)'
              % (cable_pa, cable_pa * CABLE_AREA))
        build_config(base, cable_pa, a.x_c, a.d_c, tmp)
        rc, log = run(['abaqus', 'python', 'run_analysis.py', '--config', tmp], a.dry_run)
        if rc:
            print('[PROBE] !!! LF 실행 실패 rc=%d — 중단' % rc)
            return rc
        if a.dry_run:
            continue
        rc, out = run(['abaqus', 'python', 'base_state_probe.py', odb, 'Step-GlobalTension'],
                      a.dry_run)
        m = KV.search(out)
        if rc or not m:
            print('[PROBE] !!! 프로브 파싱 실패 rc=%d' % rc)
            continue
        mean_pa, minp_pa = float(m.group(1)), float(m.group(2))
        mises_pa = float(m.group(3)) if m.group(3) else float('nan')
        rows.append({'cable_prestress_pa': cable_pa,
                     'cable_force_n': cable_pa * CABLE_AREA,
                     'centre_mean_pa': mean_pa,
                     'centre_minp_pa': minp_pa,
                     'centre_mises_pa': mises_pa,
                     'ratio_mises_1psi': mises_pa / TARGET if mises_pa == mises_pa else float('nan')})
        print('[PROBE]   mean=%.1f  minP=%.1f  Mises=%.1f Pa  (Mises %.3f x 1 psi)'
              % (mean_pa, minp_pa, mises_pa, mises_pa / TARGET))

    if a.dry_run:
        print('\n[PROBE] dry-run 종료 — config 만 생성했다:', os.path.basename(tmp))
        return 0

    if rows:
        os.makedirs(os.path.dirname(csv_path), exist_ok=True)
        new = not os.path.exists(csv_path)
        with io.open(csv_path, 'a', encoding='utf-8', newline='') as f:
            w = csv.DictWriter(f, fieldnames=['x_c', 'd_c', 'cable_prestress_pa', 'cable_force_n',
                                              'centre_mean_pa', 'centre_minp_pa', 'centre_mises_pa',
                                              'ratio_mises_1psi'])
            if new:
                w.writeheader()
            for r in rows:
                w.writerow(dict(r, x_c=a.x_c, d_c=a.d_c))
        print('\n[PROBE] CSV: %s' % csv_path)

        print('[PROBE] ---- 요약 ----')
        print('  %12s %9s %10s %10s %10s %9s'
              % ('cable[Pa]', 'F[N]', 'mean[Pa]', 'minP[Pa]', 'Mises[Pa]', 'M/1psi'))
        for r in rows:
            print('  %12.4g %9.2f %10.1f %10.1f %10.1f %9.3f'
                  % (r['cable_prestress_pa'], r['cable_force_n'], r['centre_mean_pa'],
                     r['centre_minp_pa'], r['centre_mises_pa'], r['ratio_mises_1psi']))

        # 원점 통과 최소제곱: Mises = k * cable_prestress
        num = sum(r['cable_prestress_pa'] * r['centre_mises_pa'] for r in rows
                  if r['centre_mises_pa'] == r['centre_mises_pa'])
        den = sum(r['cable_prestress_pa'] ** 2 for r in rows
                  if r['centre_mises_pa'] == r['centre_mises_pa'])
        if den:
            k = num / den
            tgt = TARGET / k
            print('  선형 기울기 k = %.4f Pa/Pa  -> 1 psi 는 CABLE_PRESTRESS ≈ %.4g Pa'
                  ' (= %.2f N/cable)' % (k, tgt, tgt * CABLE_AREA))
        print('  판정: M/1psi 가 프리스트레스에 비례하면 선형 / 포화하면 비선형(주름)')

    if a.restore:
        print('\n[PROBE] 기준 운용점 복원: CABLE_PRESTRESS=%.4g Pa (%.2f N/cable)'
              % (a.restore, a.restore * CABLE_AREA))
        build_config(base, a.restore, a.x_c, a.d_c, tmp)
        rc, _ = run(['abaqus', 'python', 'run_analysis.py', '--config', tmp], a.dry_run)
        if rc:
            print('[PROBE] !!! 복원 실패 rc=%d — 수동으로 다시 돌리세요' % rc)
            return rc

    #   스윕이 덮어쓴 점별 results txt 를 원래(HF) 기록으로 되돌린다.
    if not a.dry_run and os.path.exists(backup):
        shutil.copy2(backup, live)
        print('[PROBE] 기존 HF 결과 복원: %s' % os.path.basename(live))
    return 0


if __name__ == '__main__':
    sys.exit(main())
