#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""DISP_GLOBAL 스윕 — 중앙 최소주응력이 7000 Pa 에 도달하는 운용점을 찾는다.

    python probe_disp_sweep.py --dry-run          # config 생성/경로만 검증
    python probe_disp_sweep.py                    # LF 4점 실행 (~40 s/점)

왜 LF 만 도나: Galhofo 2022 §3.3 의 7000 Pa 은 **완전(perfect) 막의 프리스트레스 상태**에서
중앙 최소주응력이다. HF 는 기하 임퍼펙션을 넣은 뒤 같은 프리스트레스를 주므로, 운용점 질문은
LF 가 정확하고 10배 싸다.

주의 1 — `clean_lf: true` 가 필수다. `_LF_MODEL_FP` 에 DISP_GLOBAL 이 **없어서**, 지우지 않으면
  옛 운용점의 LF ODB 가 조용히 재사용된다(같은 파일명).
주의 2 — 스윕이 끝나면 기준 운용점으로 되돌린다(`--restore`, 기본 165 µm). 안 하면 이후 HF 의
  짝 LF ODB 가 마지막 disp 에 남는다.
"""
from __future__ import print_function

import argparse
import csv
import io
import json
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import aba_imperfection as A                                                # noqa: E402

KV = re.compile(r'centre_mean_pa=([-\d.eE+]+)\s+centre_minp_pa=([-\d.eE+]+)')


def build_config(base, disp, x_c, d_c, out_path):
    cfg = json.load(io.open(base, encoding='utf-8'))
    cfg['DISP_GLOBAL'] = disp
    cfg['_comment'] = (
        'Probe config generated by probe_disp_sweep.py (operating-point sweep). '
        'DISP_GLOBAL IS SET HERE on purpose - do not copy this file as a run config. '
        'All other keys are inherited from %s.' % os.path.basename(base))
    cfg['RUN'] = {
        'x_c': x_c, 'd_c': d_c,
        'fidelities': ['LF'],
        'make_seed': False, 'force_seed': False,
        'buckle': False, 'clean_lf': True,
    }
    io.open(out_path, 'w', encoding='utf-8').write(
        json.dumps(cfg, indent=2, ensure_ascii=False) + '\n')


def run(cmd, dry):
    print('  $', ' '.join(cmd))
    if dry:
        return 0, ''
    p = subprocess.Popen(cmd, cwd=HERE, stdout=subprocess.PIPE,
                         stderr=subprocess.STDOUT, universal_newlines=True)
    assert p.stdout is not None
    out = []
    for line in p.stdout:
        out.append(line)
        if 'centre_minp_pa' in line or 'RESULTS:' in line or 'Traceback' in line:
            print('     ', line.rstrip()[:200])
    return p.wait(), ''.join(out)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--x_c', type=float, default=0.2)
    ap.add_argument('--d_c', type=float, default=1e-4)
    ap.add_argument('--config', default=os.path.join('configs', 'seed.json'))
    ap.add_argument('--disps', type=float, nargs='+',
                    default=[1.65e-4, 3.3e-4, 4.95e-4, 6.6e-4])
    ap.add_argument('--restore', type=float, default=1.65e-4,
                    help='스윕 후 되돌릴 DISP_GLOBAL [m] (0 이면 생략)')
    ap.add_argument('--dry-run', action='store_true')
    a = ap.parse_args(argv)

    base = a.config if os.path.isabs(a.config) else os.path.join(HERE, a.config)
    tmp = os.path.join(HERE, 'configs', '_probe_disp.json')
    odb = os.path.join(HERE, 'aba', A.lf_odb_name(a.x_c, a.d_c))
    csv_path = os.path.join(HERE, 'results', 'probe_disp_centre.csv')
    live = os.path.join(HERE, 'results', 'results_xc%s_dc%s.txt'
                        % (A.value_tag(a.x_c), A.value_tag(a.d_c)))
    backup = os.path.join(HERE, 'results', 'probe_backup_%s' % os.path.basename(live))
    rows = []

    #   LF 런은 점별 results txt 를 'w' 로 덮어쓴다 -> 기존 HF(Arm A) 기록을 먼저 보관한다.
    if not a.dry_run and os.path.exists(live):
        shutil.copy2(live, backup)
        print('[PROBE] 기존 결과 백업: %s' % os.path.basename(backup))

    print('[PROBE] x_c=%g d_c=%g  LF ODB=%s' % (a.x_c, a.d_c, os.path.basename(odb)))
    for disp in a.disps:
        print('\n[PROBE] DISP_GLOBAL = %.1f um' % (disp * 1e6))
        build_config(base, disp, a.x_c, a.d_c, tmp)
        rc, log = run(['abaqus', 'python', 'run_analysis.py', '--config', tmp], a.dry_run)
        if rc:
            print('[PROBE] !!! LF 실행 실패 rc=%d — 중단' % rc)
            return rc
        if a.dry_run:
            continue
        rc, out = run(['abaqus', 'python', 'base_state_probe.py', odb, 'Step-GlobalTension'],
                      a.dry_run)
        m = KV.search(out)
        if rc or not m:
            print('[PROBE] !!! 프로브 파싱 실패 rc=%d' % rc)
            continue
        mean_pa, minp_pa = float(m.group(1)), float(m.group(2))
        rows.append({'disp_um': disp * 1e6, 'centre_mean_pa': mean_pa,
                     'centre_minp_pa': minp_pa, 'ratio_to_7000': minp_pa / 7000.0})
        print('[PROBE]   mean=%.1f Pa  minP=%.1f Pa  (%.3f x 7000)' % (mean_pa, minp_pa, minp_pa / 7000.0))

    if a.dry_run:
        print('\n[PROBE] dry-run 종료 — config 만 생성했다:', os.path.basename(tmp))
        return 0

    if rows:
        os.makedirs(os.path.dirname(csv_path), exist_ok=True)
        new = not os.path.exists(csv_path)
        with io.open(csv_path, 'a', encoding='utf-8', newline='') as f:
            w = csv.DictWriter(f, fieldnames=['x_c', 'd_c', 'disp_um', 'centre_mean_pa',
                                              'centre_minp_pa', 'ratio_to_7000'])
            if new:
                w.writeheader()
            for r in rows:
                w.writerow(dict(r, x_c=a.x_c, d_c=a.d_c))
        print('\n[PROBE] CSV: %s' % csv_path)

        # 원점 통과 최소제곱: sigma = k * disp
        num = sum(r['disp_um'] * r['centre_minp_pa'] for r in rows)
        den = sum(r['disp_um'] ** 2 for r in rows)
        k = num / den if den else 0.0
        print('[PROBE] ---- 요약 ----')
        print('  %10s %14s %14s %10s' % ('disp[um]', 'mean[Pa]', 'minP[Pa]', 'minP/7000'))
        for r in rows:
            print('  %10.1f %14.1f %14.1f %10.3f'
                  % (r['disp_um'], r['centre_mean_pa'], r['centre_minp_pa'], r['ratio_to_7000']))
        if k > 0:
            print('  선형 기울기 k = %.4f Pa/um  -> 7000 Pa 는 DISP_GLOBAL ≈ %.1f um'
                  % (k, 7000.0 / k))
            r0 = rows[0]
            print('  첫 점 기준 선형 외삽: %.1f um' % (r0['disp_um'] * 7000.0 / r0['centre_minp_pa']))
        print('  판정: minP/7000 이 disp 에 비례하면 선형 / 포화하면 비선형(주름)')

    if a.restore:
        print('\n[PROBE] 기준 운용점 복원: DISP_GLOBAL=%.1f um' % (a.restore * 1e6))
        build_config(base, a.restore, a.x_c, a.d_c, tmp)
        rc, _ = run(['abaqus', 'python', 'run_analysis.py', '--config', tmp], a.dry_run)
        if rc:
            print('[PROBE] !!! 복원 실패 rc=%d — 수동으로 다시 돌리세요' % rc)
            return rc

    #   스윕이 덮어쓴 점별 results txt 를 원래(HF) 기록으로 되돌린다.
    if not a.dry_run and os.path.exists(backup):
        shutil.copy2(backup, live)
        print('[PROBE] 기존 HF 결과 복원: %s' % os.path.basename(live))
    return 0


if __name__ == '__main__':
    sys.exit(main())
